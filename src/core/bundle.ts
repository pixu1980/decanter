// The `.app` bundle.
//
// macOS attributes a process to the `.app` whose `Contents/MacOS` holds the
// running executable. Game Porting Toolkit's own bundle sets `LSUIElement`
// (accessory app: no Dock icon, no menu, no ⌘Q), so the bundle must host the
// Wine loader itself. We copy the tiny launchers (`wine64`,
// `wine64-preloader`, `wineserver`) into `Contents/MacOS` and symlink the heavy
// `lib`/`share` directories. Wine then adopts our `Info.plist`, which is what
// gives the game a normal app menu and a working ⌘Q.
//
// docs: docs/architecture.md

import { join } from "node:path";
import { exec, isDryRun } from "./exec.ts";
import { exists, mkdirp, writeText } from "./fsx.ts";
import type { GamePaths } from "./game.ts";
import { die, log } from "./log.ts";
import { gameDir } from "./paths.ts";
import type { GameProfile } from "./profile.ts";
import type { WineRuntime } from "./wine.ts";
import { winePaths } from "./wine.ts";

/** Is the bundle hosting its own Wine loader? */
export function bundleRuntimeReady(app: string): boolean {
  return exists(join(app, "Contents", "MacOS", "wine64"));
}

/** Build (or rebuild) the game's `.app`. */
export async function buildApp(
  profile: GameProfile,
  paths: GamePaths,
  wine: WineRuntime,
): Promise<void> {
  log(`building app bundle: ${paths.app}`);
  if (!isDryRun() && !exists(wine.distExe)) {
    die(`${wine.label} not found at ${wine.app} — run: steam-mac setup ${profile.slug}`);
  }

  await mkdirp(join(paths.app, "Contents", "MacOS"));
  await mkdirp(join(paths.app, "Contents", "Resources"));

  if (isDryRun()) {
    log(`dry-run: copy the ${wine.label} loader into ${paths.app}/Contents/MacOS`);
    log(`dry-run: link lib and share to the ${wine.label} runtime`);
    log(`dry-run: write Contents/MacOS/launch and Contents/Info.plist`);
    return;
  }

  const macos = join(paths.app, "Contents", "MacOS");
  await exec("cp", ["-f", wine.distExe, join(macos, "wine64")]);
  if (wine.preloader) {
    await exec("cp", ["-f", wine.preloader, join(macos, "wine64-preloader")]);
  } else {
    await exec("rm", ["-f", join(macos, "wine64-preloader")], { allowFailure: true });
  }
  await exec("cp", ["-f", wine.distServer, join(macos, "wineserver")]);

  const { lib, share } = winePaths(wine);
  await exec("ln", ["-sfn", lib, join(paths.app, "Contents", "lib")]);
  await exec("ln", ["-sfn", share, join(paths.app, "Contents", "share")]);

  const iconSource = join(gameDir(profile.slug), profile.icon);
  if (profile.icon && exists(iconSource)) {
    await exec("cp", ["-f", iconSource, join(paths.app, "Contents", "Resources", "icon.icns")]);
  }

  await writeLaunch(profile, paths);
  await writeInfoPlist(profile, paths);
  await exec("touch", [paths.app]);
}

/** Write `Contents/MacOS/launch`, the bundle's executable. */
async function writeLaunch(profile: GameProfile, paths: GamePaths): Promise<void> {
  const script = `#!/bin/zsh
# Generated by steam-mac. Hosts the Wine loader so the game gets a real macOS
# app menu and Cmd+Q. Rebuild with: steam-mac app ${profile.slug}
set -euo pipefail
HERE="\${0:A:h}"
BUNDLE="\${HERE:h:h}"
export WINEPREFIX=${shellQuote(paths.prefix)}
export WINEESYNC=\${WINEESYNC:-1}
export WINEMSYNC=\${WINEMSYNC:-1}
export WINEDEBUG=\${WINEDEBUG:--all}
cd ${shellQuote(paths.gameDir)}
exec "\$HERE/wine64" ${shellQuote(profile.exe)} "\$@"
`;
  const target = join(paths.app, "Contents", "MacOS", "launch");
  await writeText(target, script);
  await exec("chmod", ["+x", target]);
}

/** Write `Contents/Info.plist`. */
async function writeInfoPlist(profile: GameProfile, paths: GamePaths): Promise<void> {
  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>${xml(profile.name)}</string>
  <key>CFBundleIdentifier</key><string>${xml(profile.bundleId)}</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>CFBundleShortVersionString</key><string>${xml(profile.version)}</string>
  <key>CFBundleVersion</key><string>${xml(profile.version)}</string>
  <key>CFBundleAllowMixedLocalizations</key><true/>
  <key>CFBundleDevelopmentRegion</key><string>English</string>
  <key>NSPrincipalClass</key><string>WineApplication</string>
  <key>LSMinimumSystemVersion</key><string>${profile.minMacos}.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict></plist>
`;
  const target = join(paths.app, "Contents", "Info.plist");
  await writeText(target, plist);
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function xml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
